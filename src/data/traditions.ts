import type { AxisDatum, AxisId, Church, Provenance } from '../domain/types';

/**
 * Denominational archetypes.
 *
 * These describe *families*, not congregations. A given PCA church may be more
 * missional than the archetype and a given Southern Baptist church more
 * Reformed; the archetypes exist so that whole categories can be ruled in or
 * out quickly, and so a real church can inherit sensible starting values that
 * you then correct from what the church itself says.
 *
 * Confidence is set per datum, and it means something specific here: how
 * *definitional* the value is for the family. Paedobaptism is definitional for
 * Presbyterians (0.95). Worship style is not definitional for anybody (0.4-0.5).
 */
function d(
  value: number,
  confidence: number,
  provenance: Provenance = 'inferred',
  note?: string,
): AxisDatum {
  return { value, confidence, provenance, note };
}

type Values = Partial<Record<AxisId, AxisDatum>>;

function tradition(
  id: string,
  name: string,
  locale: string,
  summary: string,
  values: Values,
): Church {
  return {
    id,
    name,
    kind: 'tradition',
    locale,
    stage: 'researching',
    summary,
    notes: '',
    values,
    visits: [],
  };
}

